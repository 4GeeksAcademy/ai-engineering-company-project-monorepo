"""Shared telemetry event models — ingestion-layer contract.

Source of truth: docs/event-envelope.md (envelope field definitions) and
docs/event-schemas.json (the full, closed per-event-type contract used by
the generated ``app.models.events`` module).

``TelemetryEvent`` here is deliberately the *generic* envelope shape, not
the 20-way discriminated union in ``app.models.events``: the ingestion
endpoint accepts any event whose envelope is well-formed and whose
``event_type`` follows the project's naming convention, without hard-coding
the current closed list of 20 types into this layer. Enforcing the full
per-event-type ``properties`` allowlist (as ``event-schemas.json`` does) is
left to a later phase — see the assumptions below.

Assumptions made where docs/event-envelope.md leaves a detail undefined for
a *generic* (non-discriminated) model:
- ``properties`` is typed as an open ``dict[str, object]`` here, since a
  single shared model cannot statically carry 20 different closed property
  schemas at once; the closed allowlist per ``event_type`` is already
  enforced by ``app.models.events`` and ``docs/event-schemas.json`` for
  callers that validate against a *specific* event type.
- ``event_type`` is validated only against the project's naming convention
  (snake_case, entity_action — see docs/event-envelope.md section 3), not
  against the fixed list of 20 known names, so the ingestion endpoint does
  not need to be redeployed every time a new event type is added to the
  catalog.
- ``eventId`` is validated as any UUID version, not strictly UUID v4 (the
  envelope doc says "UUID v4" is the generation convention, but validating
  the version strictly would reject a syntactically valid UUID generated by
  a non-conformant client for no operational benefit at the ingestion
  layer).
"""

from __future__ import annotations

from typing import Annotated, Any
from uuid import UUID

from pydantic import AwareDatetime, BaseModel, ConfigDict, StringConstraints

EventType = Annotated[
    str,
    StringConstraints(pattern=r"^[a-z]+(_[a-z]+)+$"),
]
"""snake_case, entity_action convention (docs/event-envelope.md section 3),
e.g. ``inbound_order_created``, ``session_expired``."""

SchemaVersion = Annotated[str, StringConstraints(pattern=r"^\d+\.\d+\.\d+$")]
"""Semver, e.g. "1.0.0" (docs/event-envelope.md: `schemaVersion`)."""


class TelemetryEvent(BaseModel):
    """One telemetry event envelope (docs/event-envelope.md section 1).

    All 8 envelope keys are always present. ``sessionId``, ``userId`` and
    ``requestId`` admit ``null`` for the specific, documented cases in the
    plan (no session concept exists yet, identity not resolved yet, no
    request-id middleware yet) — never invented to fill a gap.
    """

    model_config = ConfigDict(extra="forbid")

    eventId: UUID
    timestamp: AwareDatetime
    sessionId: str | None
    userId: str | None
    event_type: EventType
    schemaVersion: SchemaVersion
    requestId: str | None
    properties: dict[str, object]


class TelemetryEventBatch(BaseModel):
    """Strict shape of `{"events": [...]}` where every element is already
    known to be a valid TelemetryEvent. Not used as the router's request
    model (see RawTelemetryEventBatch) — FastAPI would reject the *entire*
    request if even one element failed Pydantic validation against
    `list[TelemetryEvent]`, which contradicts the per-event validation
    this endpoint performs. Kept for any caller that already has a batch
    of validated events and wants the shape for its own use (e.g. tests
    building a known-valid payload).
    """

    model_config = ConfigDict(extra="forbid")

    events: list[TelemetryEvent]


class RawTelemetryEventBatch(BaseModel):
    """The router's actual request model for POST /telemetry/events.

    Validates only the outer envelope — `events` must be a JSON array, but
    each element is `Any` so a malformed element never fails the request
    at FastAPI's parsing layer. Each element is validated individually via
    `TelemetryEvent.model_validate(raw_event)` inside the handler, so one
    bad event is rejected and counted without affecting the rest of the
    batch. `events` is still a required key — a missing key, a non-array
    `events` value, or malformed JSON all still fail at this layer with
    the project's standard request-validation response (422).
    """

    model_config = ConfigDict(extra="forbid")

    events: list[Any]
